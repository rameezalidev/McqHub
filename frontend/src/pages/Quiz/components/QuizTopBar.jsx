import { AutosaveIcon, QuizTimerIcon } from "../../../components/icons/Icons";

function QuizTopBar({ categoryName, questionSource, currentQuestion, questionsLength, progressPercent, formattedTimer, timeLeft }) {
  return (
    <div className="quiz-top-bar">
      <div className="quiz-category-chip">
        <span className="category-dot"></span>
        <span className="category-name-text">{categoryName || "Knowledge Quiz"}</span>
      </div>

      {questionSource && (
        <div
          style={{
            display: "inline-flex",
            alignItems: "center",
            padding: "6px 12px",
            borderRadius: "999px",
            fontSize: "0.72rem",
            fontWeight: 700,
            background: questionSource === "ai" ? "#eef2ff" : "#ecfdf5",
            color: questionSource === "ai" ? "#4338ca" : "#166534",
            marginTop: "6px",
          }}
        >
          {questionSource === "ai" ? "Generated by AI" : "Fetched from DB"}
        </div>
      )}

      <div className="quiz-progress-section">
        <span className="quiz-progress-label">
          Question {currentQuestion + 1} of {questionsLength}
        </span>
        <div className="quiz-progress-bar-bg">
          <div className="quiz-progress-bar-fill" style={{ width: `${progressPercent}%` }}></div>
        </div>
      </div>

      <div className={`quiz-timer-badge ${timeLeft <= 10 ? "timer-warning" : ""}`}>
        <QuizTimerIcon />
        <span className="timer-text">{formattedTimer}</span>
      </div>

      <div className="quiz-autosave-indicator">
        <AutosaveIcon />
      </div>
    </div>
  );
}

export default QuizTopBar;
